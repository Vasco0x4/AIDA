def _escape(s: str) -> str:
    return (s or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _figures_html(figures) -> str:
    """Render embedded evidence screenshots as numbered figures (data-URI imgs)."""
    if not figures:
        return ""
    parts = ["<h2>Evidence — Screenshots</h2>"]
    for i, fig in enumerate(figures, start=1):
        uri = fig.get("data_uri")
        if not uri:
            continue
        cap = _escape(fig.get("caption") or "")
        parts.append(
            f"<figure class='evidence'><img src='{uri}'>"
            f"<figcaption>Figure {i}{(' — ' + cap) if cap else ''}</figcaption></figure>")
    return "".join(parts) if len(parts) > 1 else ""


def image_data_uri(data: bytes, content_type: str = "image/png") -> str:
    """Build a base64 data: URI WeasyPrint can embed into the PDF. The
    content_type is validated (it can originate from a client upload header) so
    it cannot break out of the URI and inject arbitrary HTML/attributes."""
    ct = content_type if (content_type and _IMAGE_CT_RE.match(content_type)) else "image/png"
    return f"data:{ct};base64,{base64.b64encode(data).decode()}"


def markdown_to_pdf(markdown_text: str, title: str = "Vulnerability Report",
                    figures: Optional[list] = None) -> bytes:
    """Render a Markdown report to PDF bytes, embedding any evidence ``figures``
    ([{data_uri, caption}]) as a Screenshots section at the end — like a human
    attaches annotated screenshots to a bug-bounty report."""
    body_html = md_lib.markdown(
        markdown_text or "",
        extensions=["fenced_code", "tables", "sane_lists"],
        output_format="html5",
    )
    safe_title = _escape(title or "Vulnerability Report")
    doc = (
        f"<!doctype html><html><head><meta charset='utf-8'><title>{safe_title}</title>"
        f"<style>{_REPORT_CSS}</style></head><body>{body_html}"
        f"{_figures_html(figures)}"
        f"<div class='aida-footer'>Generated by AIDA — submission-ready report. "
        f"Confidential; for the receiving security program only.</div>"
        f"</body></html>"
    )
    # url_fetcher blocks any http/https/file resource the HTML might reference
    # (SSRF/local-file read guard) — only embedded data: URIs are allowed.
    return HTML(string=doc, url_fetcher=_blocked_url_fetcher).write_pdf()
