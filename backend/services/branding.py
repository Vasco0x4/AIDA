"""
Report branding (E4) — org identity on every generated report.

Stored as a single platform setting (``report_branding`` JSON): organization
name, tagline, classification banner, primary color, and an optional logo
(data URI). Applied to the cover page and footers of PDF reports so a report
generated by AIDA reads as the operator's own deliverable.
"""
from __future__ import annotations

import re
from typing import Optional

from sqlalchemy.orm import Session

from models.platform_settings import PlatformSettings

_SETTING_KEY = "report_branding"
_MAX_LOGO_BYTES = 300 * 1024

DEFAULT_BRANDING = {
    "organization": "AIDA",
    "tagline": "AI-Driven Security Assessment",
    "classification": "Confidential",
    "primary_color": "#0b3d91",
    "logo_data_uri": "",
}

_COLOR_RE = re.compile(r"^#[0-9a-fA-F]{6}$")


def get_branding(db: Session) -> dict:
    row = db.query(PlatformSettings).filter(
        PlatformSettings.key == _SETTING_KEY).first()
    out = dict(DEFAULT_BRANDING)
    if row:
        try:
            import json
            stored = json.loads(row.value) if isinstance(row.value, str) else row.value
            if isinstance(stored, dict):
                for k in DEFAULT_BRANDING:
                    if stored.get(k) is not None:
                        out[k] = stored[k]
        except Exception:
            pass
    return out


def _save(db: Session, branding: dict) -> None:
    import json
    row = db.query(PlatformSettings).filter(
        PlatformSettings.key == _SETTING_KEY).first()
    value = json.dumps(branding)
    if row:
        row.value = value
    else:
        db.add(PlatformSettings(key=_SETTING_KEY, value=value,
                                description="Report branding (org, classification, color, logo)"))
    db.commit()


def update_branding(db: Session, *, organization: Optional[str] = None,
                    tagline: Optional[str] = None,
                    classification: Optional[str] = None,
                    primary_color: Optional[str] = None) -> dict:
    """Validate and apply branding field updates. Raises ValueError on bad input."""
    branding = get_branding(db)
    if organization is not None:
        organization = organization.strip()
        if not 1 <= len(organization) <= 120:
            raise ValueError("organization must be 1-120 characters")
        branding["organization"] = organization
    if tagline is not None:
        branding["tagline"] = tagline.strip()[:200]
    if classification is not None:
        classification = classification.strip()
        if not 1 <= len(classification) <= 60:
            raise ValueError("classification must be 1-60 characters")
        branding["classification"] = classification
    if primary_color is not None:
        if not _COLOR_RE.match(primary_color):
            raise ValueError("primary_color must be a #rrggbb hex color")
        branding["primary_color"] = primary_color
    _save(db, branding)
    return branding


def _sniff_image(data: bytes) -> Optional[str]:
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png"
    if data.startswith(b"\xff\xd8\xff"):
        return "image/jpeg"
    head = data.lstrip()[:300].lower()
    if head.startswith(b"<?xml") or head.startswith(b"<svg"):
        return "image/svg+xml"
    return None


def save_logo(db: Session, data: bytes) -> dict:
    """Validate and store an uploaded logo (PNG/JPEG/SVG, ≤300KB) as a data URI."""
    if not data:
        raise ValueError("Empty logo upload")
    if len(data) > _MAX_LOGO_BYTES:
        raise ValueError(f"Logo too large ({len(data)} bytes; max {_MAX_LOGO_BYTES})")
    ctype = _sniff_image(data)
    if not ctype:
        raise ValueError("Unsupported logo format — expected PNG, JPEG or SVG")
    import base64
    branding = get_branding(db)
    branding["logo_data_uri"] = (f"data:{ctype};base64,"
                                 + base64.b64encode(data).decode("ascii"))
    _save(db, branding)
    return branding


def clear_logo(db: Session) -> dict:
    branding = get_branding(db)
    branding["logo_data_uri"] = ""
    _save(db, branding)
    return branding
