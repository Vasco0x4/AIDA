def _seed_full(db):
    from models.assessment import Assessment

    asn = Assessment(name="ACME Web", scope="acme.com", client_name="ACME Corp")
    db.add(asn)
    db.flush()

    db.add_all([
        Card(assessment_id=asn.id, card_type="finding", title="SQLi in login",
             severity="HIGH", target_service="web", cvss_score=8.1,
             status="confirmed", technical_analysis="Injection in the login form.",
             proof="curl -d \"' OR 1=1--\" http://t/login", notes="Use prepared statements."),
        Card(assessment_id=asn.id, card_type="finding", title="Reflected XSS",
             severity="MEDIUM", target_service="search"),
        Card(assessment_id=asn.id, card_type="observation", title="Old header"),
        Card(assessment_id=asn.id, card_type="info", title="Tech stack"),
    ])
    db.add(ReconData(assessment_id=asn.id, data_type="subdomain", name="app.acme.com"))
    db.add(Credential(assessment_id=asn.id, credential_type="basic_auth",
                      name="Admin account", placeholder="BASIC_AUTH_ADMIN",
                      username="admin", password="s3cret", service="Web App"))
    db.add(TimelineEvent(assessment_id=asn.id, phase="recon", event_type="recon",
                         title="Found subdomain", description="via subfinder"))
    db.add(TimelineEvent(assessment_id=asn.id, phase="exploitation", event_type="command",
                         title="Ran exploit", severity="HIGH"))
    db.flush()
    finding = db.query(Card).filter(Card.title == "SQLi in login").one()
    db.add(Artifact(assessment_id=asn.id, card_id=finding.id, kind="screenshot",
                    filename="poc.png", content_type="image/png", data=b"\x89PNG"))
    db.commit()
    db.refresh(asn)
    return asn


def test_generate_markdown_report_full(db):
    asn = _seed_full(db)
    out = generate_markdown_report(db, asn.id)

    assert out.startswith("# Security Assessment Report — ACME Web")
    assert "- **Client:** ACME Corp" in out
    assert "- **Scope:** acme.com" in out
    assert "- **Risk score:** HIGH" in out
    assert "- **Findings:** 2 (HIGH: 1, MEDIUM: 1)" in out
    assert "- **Recon items:** 1 · **Credentials:** 1" in out
    # Kill chain ordered recon → exploitation
    assert out.index("### Reconnaissance") < out.index("### Exploitation")
    assert "- `Recon`" not in out and "Found subdomain — via subfinder" in out
    # Findings sorted worst-first with evidence count
    assert "### 1. [HIGH] SQLi in login" in out
    assert "### 2. [MEDIUM] Reflected XSS" in out
    assert "_target: `web` · CVSS 8.1 · status: confirmed_" in out
    assert "_Evidence: 1 screenshot(s) attached in the PDF._" in out
    # Recon section
    assert "- **subdomain**: app.acme.com" in out
    # Secrets masked by default
    assert "••••••••" in out and "s3cret" not in out
    assert "**basic_auth** admin @ Web App" in out


def test_generate_markdown_report_include_secrets(db):
    asn = _seed_full(db)
