async def test_generate_pdf_report_methodology_and_placeholder(db, fake_pdf, fake_docker):
    from models.assessment import Assessment

    asn = Assessment(name="Meth", workspace_path="/workspace/meth",
                     container_name="c1")
    db.add(asn)
    db.commit()
    db.refresh(asn)

    # File exists and has real content → methodology section rendered
    fake_docker.responses = [
        {"success": True, "stdout": "exists"},
        {"success": True, "stdout": "# How we tested\n\nRan the full suite."},
    ]
    await rs.generate_pdf_report(db, asn.id)
    assert "How we tested" in FakeHTML.last_html
    assert any("methodology.md" in c and c.startswith("cat ") for c in fake_docker.commands)

    # Still the default template → section omitted
    fake_docker.responses = [
        {"success": True, "stdout": "exists"},
        {"success": True, "stdout": "# Methodology Report\n\n> Generated by AIDA AI at the end of the engagement.\n"},
    ]
    await rs.generate_pdf_report(db, asn.id)
    assert "Generated by AIDA AI" not in FakeHTML.last_html

    # File missing → no docker cat, no crash
    fake_docker.responses = [{"success": False, "stderr": "No such file"}]
    await rs.generate_pdf_report(db, asn.id)
    assert "How we tested" not in FakeHTML.last_html


