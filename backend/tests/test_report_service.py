# ── line classification / code wrapping ───────────────────────────────────────

def test_classify_line_strong_weak_prose():
    assert _classify_line("curl -s http://x") == "strong"
    assert _classify_line("$ nmap -sV target") == "strong"
    assert _classify_line("→ 200 OK") == "strong"
    assert _classify_line("") == "prose"
    assert _classify_line("just a sentence") == "prose"
    assert _classify_line("POST /api/login") == "weak"        # verb + path
    assert _classify_line("POST data is sent") == "prose"      # verb + prose
    assert _classify_line("# current state") == "weak"         # short comment
    assert _classify_line("## A real markdown heading that is long enough") == "prose"


def test_wrap_unfenced_code_multiline_block():
    text = "# check auth\ncurl -s -u admin:admin http://t/api\n→ HTTP 403"
    wrapped = _wrap_unfenced_code(text)
    assert wrapped.startswith("```")
    assert wrapped.endswith("```")
    assert wrapped.count("```") == 2  # exactly one fence pair


def test_wrap_unfenced_code_single_strong_line():
    assert _wrap_unfenced_code("nmap -sV 10.0.0.1") == "```\nnmap -sV 10.0.0.1\n```"
    # Weak signal alone is left as prose
    assert _wrap_unfenced_code("POST /api/login") == "POST /api/login"


def test_wrap_unfenced_code_leaves_fenced_and_prose_alone():
    fenced = "```bash\ncurl http://x\n```\n"
    assert _wrap_unfenced_code(fenced) == fenced
    prose = "This is a normal paragraph\nspanning two lines of plain text."
    assert _wrap_unfenced_code(prose) == prose
    assert _wrap_unfenced_code("") == ""
    # Prose paragraph + code paragraph coexist: only the code block is fenced
    mixed = _wrap_unfenced_code("Some intro text.\n\n$ whoami\n→ root")
    assert "Some intro text." in mixed
    assert "```" in mixed


def test_render_markdown_converts_and_autofences():
    html = _render_markdown("# Title\n\n**bold** and `code`")
    assert "<h1>Title</h1>" in html
    assert "<strong>bold</strong>" in html
    assert "<code>code</code>" in html
    assert _render_markdown("") == ""
    # Unfenced shell dump is fenced before markdown sees it
    html = _render_markdown("curl -s http://t/api\n→ HTTP 500")
    assert "<pre><code" in html


def test_format_recon_details():
    assert _format_recon_details(None) == "—"
    assert _format_recon_details("") == "—"
    assert _format_recon_details({}) == "—"
    assert _format_recon_details({"port": 80, "service": "nginx"}) == "port: 80 · service: nginx"
    assert _format_recon_details(["a", "b"]) == "a, b"
    assert _format_recon_details([]) == "—"
    assert _format_recon_details(42) == "42"
    assert _format_recon_details("plain") == "plain"


