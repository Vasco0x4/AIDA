"""Create first-install configuration without replacing existing secrets."""
import os
from pathlib import Path
import re
import secrets
import sys


def bootstrap(directory: Path) -> bool:
    target = directory / '.env'
    if target.exists():
        return False
    project = os.environ.get('AIDA_PROJECT_NAME', 'aida-prod')
    if not re.fullmatch(r'[a-z0-9][a-z0-9_-]*', project):
        raise ValueError('AIDA_PROJECT_NAME must contain lowercase letters, digits, _ or -')
    front = os.environ.get('FRONTEND_PORT', '31337')
    back = os.environ.get('BACKEND_PORT', '8000')
    for value in (front, back):
        if not value.isdigit() or not 1 <= int(value) <= 65535:
            raise ValueError('Ports must be integers between 1 and 65535')
    values = {
        'AIDA_PROJECT_NAME': project,
        'AIDA_VOLUME_PREFIX': project.replace('-', '_'),
        'POSTGRES_USER': 'aida',
        'POSTGRES_PASSWORD': secrets.token_hex(32),
        'POSTGRES_DB': 'aida_assessments',
        'POSTGRES_HOST': 'postgres',
        'POSTGRES_PORT': '5432',
        'SECRET_KEY': secrets.token_hex(48),
        'ENVIRONMENT': 'production',
        'DEBUG': 'false',
        'FRONTEND_BIND': '127.0.0.1',
        'FRONTEND_PORT': front,
        'BACKEND_BIND': '127.0.0.1',
        'BACKEND_PORT': back,
        'BACKEND_CORS_ORIGINS': f'http://localhost:{front},http://127.0.0.1:{front}',
        'BACKEND_IMAGE': f'{project}-backend:local',
        'FRONTEND_IMAGE': f'{project}-frontend:local',
        'PENTEST_IMAGE': 'vasco0x4/aida-pentest:latest',
        'PENTEST_CONTAINER_NAME': f'{project}-pentest',
        'DEFAULT_CONTAINER_NAME': f'{project}-pentest',
        'BACKEND_API_URL': f'http://127.0.0.1:{back}/api',
    }
    try:
        fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        return False
    with os.fdopen(fd, 'w', encoding='utf-8', newline='\n') as stream:
        stream.write('# Generated by ./start.sh. Private: do not commit or share.\n')
        stream.writelines(f'{key}={value}\n' for key, value in values.items())
    return True


if __name__ == '__main__':
    directory = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / 'backend'
    print('Created backend/.env with unique secrets.' if bootstrap(directory) else 'Existing configuration preserved.')
