#!/usr/bin/env bash
# ==============================================================================
# AIDA — start the platform
# ==============================================================================
#   ./start.sh          (same as `aida start`)
#       Web UI on https://<this machine>:31337 (self-signed certificate),
#       reachable from your network. Images are pulled from Docker Hub.
#
#   ./start.sh --dev    Contributors: build from source, hot reload,
#                       Vite on http://localhost:5173
#
# Environment overrides (rarely needed):
#   AIDA_PORT=8443      use another port if 31337 is taken
#   AIDA_BIND=127.0.0.1 only reachable from this machine
#   AIDA_BUILD=1        build backend + frontend images from source
# ==============================================================================

set -euo pipefail
# shellcheck source=scripts/common.sh
source "$(cd "$(dirname "$0")" && pwd)/scripts/common.sh"
cd "$AIDA_ROOT"

DEV=false

usage() {
    cat <<EOF
Usage: aida start [--dev]

Starts AIDA. The web UI is served over HTTPS on port ${AIDA_PORT}
(self-signed certificate) and is reachable from your local network.

  --dev     Contributor mode: build from source with hot reload
            (UI on http://localhost:5173)

Environment: AIDA_PORT (default 31337), AIDA_BIND (default 0.0.0.0),
AIDA_BUILD=1 to build images from source.
EOF
}

while [[ $# -gt 0 ]]; do
    case $1 in
        --dev|-d) DEV=true ;;
        --help|-h) usage; exit 0 ;;
        # Flags from the old multi-mode start.sh. AIDA now always runs in one
        # mode, so explain instead of failing.
        --lan|-l|--container|--fast|-f)
            warn "$1 is no longer needed: AIDA is always served on https://<host>:${AIDA_PORT}." ;;
        --lan-port)
            warn "--lan-port was removed. Use: AIDA_PORT=${2:-8443} aida start"
            [[ $# -gt 1 ]] && shift ;;
        --domain|--domain=*|--email|--email=*)
            if [[ $1 == --domain* ]]; then
                warn "--domain was removed. AIDA should not be exposed on the internet;" \
                     "put your own reverse proxy in front of https://localhost:${AIDA_PORT} if you need it."
            fi
            [[ ($1 == --domain || $1 == --email) && $# -gt 1 ]] && shift ;;
        --localhost)
            warn "--localhost (running commands directly on the host) was removed." \
                 "Commands run in the aida-pentest container." ;;
        *) error "Unknown option: $1"; usage; exit 1 ;;
    esac
    shift
done

if $DEV; then
    COMPOSE_FILES=(-f docker-compose.yml -f docker-compose.dev.yml)
else
    COMPOSE_FILES=(-f docker-compose.yml)
fi

# ==============================================================================
# Checks
# ==============================================================================

require_docker
detect_compose
COMPOSE=("${COMPOSE_BIN[@]}" --project-directory "$AIDA_ROOT" "${COMPOSE_FILES[@]}")

# ==============================================================================
# Clean up what older versions left behind
# ==============================================================================

migrate_old_install() {
    # Overlays generated by the old --lan/--domain modes.
    rm -f .aida/Caddyfile .aida/docker-compose.caddy-reset.yml \
          .aida/docker-compose.caddy-ports.yml .aida/mode-config

    # Localhost deployment mode: stop its host daemon and go back to the
    # container (the agent-container launcher refuses to run otherwise).
    if [[ "$(cat .aida/deployment-mode 2>/dev/null || true)" == "localhost" ]]; then
        warn "Localhost mode was removed — commands now run in the aida-pentest container."
        echo "container" > .aida/deployment-mode
    fi
    local pid_file="$HOME/.aida/host-agent.pid"
    if [[ -f "$pid_file" ]]; then
        kill "$(cat "$pid_file")" 2>/dev/null || true
        rm -f "$pid_file" "$HOME/.aida/host-agent.sock"
    fi

    # Containers with our names created from another folder (another clone,
    # an old docker-compose.hub.yml...) block `compose up`. Their data lives
    # in named volumes, so removing the containers is safe.
    local name project
    for name in aida_caddy aida_frontend aida_backend aida_postgres aida_docker_proxy aida-pentest; do
        project=$(docker inspect -f '{{index .Config.Labels "com.docker.compose.project"}}' "$name" 2>/dev/null) || continue
        if [[ "$project" != "aida" ]]; then
            docker rm -f "$name" >/dev/null
            log "Removed old container $name (data kept)"
        fi
    done
}

mkdir -p "$AIDA_STATE_DIR" "$HOME/.aida/workspaces" backend/logs
migrate_old_install

# ==============================================================================
# Configuration (created once, kept across updates)
# ==============================================================================

random_string() {
    # $1 = length, $2 = alphabet. `|| true`: tr is killed by SIGPIPE once
    # head has enough, which pipefail would otherwise treat as a failure.
    { LC_ALL=C tr -dc "$2" </dev/urandom 2>/dev/null || true; } | head -c "$1"
}

if [[ ! -f backend/.env ]]; then
    cp backend/.env.docker backend/.env
    log "Created backend/.env"
fi
# JWT signing key. The backend can generate one itself, but it couldn't
# persist it from inside the container, so do it here. (The old published
# default doesn't count.)
if grep -q '^SECRET_KEY=aida-secret-key-change-in-production' backend/.env; then
    sed -i.bak '/^SECRET_KEY=aida-secret-key-change-in-production/d' backend/.env
    rm -f backend/.env.bak
fi
if ! grep -qE '^SECRET_KEY=.{32,}' backend/.env; then
    printf '\n# Generated by start.sh — keep secret\nSECRET_KEY=%s\n' \
        "$(random_string 64 'A-Za-z0-9')" >> backend/.env
fi
chmod 600 backend/.env

# One-time code that protects the "create first admin" screen. The UI is
# reachable from the network, so without it anyone nearby could claim the
# admin account before you do.
if [[ ! -s "$AIDA_SETUP_CODE_FILE" ]]; then
    code=$(random_string 8 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789')
    echo "${code:0:4}-${code:4:4}" > "$AIDA_SETUP_CODE_FILE"
    chmod 600 "$AIDA_SETUP_CODE_FILE"
fi
AIDA_SETUP_CODE=$(cat "$AIDA_SETUP_CODE_FILE")
export AIDA_SETUP_CODE AIDA_PORT

# Remember a custom port so `aida status`, `aida doctor`... use it too.
if [[ "$AIDA_PORT" == 31337 ]]; then
    rm -f "$AIDA_STATE_DIR/port"
else
    echo "$AIDA_PORT" > "$AIDA_STATE_DIR/port"
fi

# ==============================================================================
# Ports
# ==============================================================================

check_port() {
    local port=$1 what=$2 owner
    owner=$(port_owner "$port")
    [[ -z "$owner" ]] && return 0
    if [[ "$port" == "$AIDA_PORT" ]]; then
        die "Port $port ($what) is already used by '$owner'." \
            "Stop that program, or pick another port: AIDA_PORT=8443 aida start"
    fi
    die "Port $port ($what) is already used by '$owner'." "Stop that program and run this again."
}

if $DEV; then
    check_port 5173 "web UI (dev)"
else
    check_port "$AIDA_PORT" "web UI"
fi
check_port 8000 "backend API"

# ==============================================================================
# Images
# ==============================================================================

# Exegol users run their own container; don't start ours.
SERVICES=()
while IFS= read -r svc; do
    [[ "$svc" == "aida-pentest" && "$(cat .aida/container-preference 2>/dev/null || true)" == "exegol" ]] && continue
    SERVICES+=("$svc")
done < <(compose config --services)

if $DEV || [[ "${AIDA_BUILD:-}" == "1" ]]; then
    section "Building backend and frontend from source"
    compose build backend frontend
fi

# Which images to download:
#  - the ones not on this machine yet (first start);
#  - all of them after the code changed (git pull / aida update), so the
#    containers run the same version as this checkout;
#  - a frontend image left over from the old --dev mode (Vite, not Nginx).
image_missing() {
    local image=$1
    docker image inspect "$image" >/dev/null 2>&1 || return 0
    if [[ "$image" == vasco0x4/aida-frontend:* ]] \
        && docker image inspect -f '{{json .Config.ExposedPorts}}' "$image" | grep -q 5173; then
        return 0
    fi
    return 1
}

# Image of one service, read from the resolved config. (`compose config
# --images <svc>` also lists the images of its dependencies.)
CONFIG_YAML=$(compose config)
service_image() {
    awk -v svc="$1" '
        /^services:/              { in_s = 1; next }
        /^[^ ]/                   { in_s = 0 }
        in_s && /^  [^ ][^ ]*:$/  { cur = substr($1, 1, length($1) - 1); next }
        in_s && cur == svc && /^    image: / { print $2; exit }
    ' <<<"$CONFIG_YAML"
}

head_commit=$(git rev-parse HEAD 2>/dev/null || echo unknown)
last_pull=$(cat .aida/last-pull 2>/dev/null || true)
to_pull=()
big_download=false   # backend / pentest images missing: a real first install
for svc in "${SERVICES[@]}"; do
    image=$(service_image "$svc")
    [[ -z "$image" ]] && continue
    if $DEV && [[ "$svc" == backend || "$svc" == frontend ]]; then
        continue    # built above
    fi
    if image_missing "$image"; then
        to_pull+=("$svc")
        [[ "$svc" == backend || "$svc" == aida-pentest ]] && big_download=true
    elif ! $DEV && [[ "${AIDA_BUILD:-}" != "1" && "$last_pull" != "$head_commit" ]]; then
        to_pull+=("$svc")
    fi
done

if [[ ${#to_pull[@]} -gt 0 ]]; then
    if $big_download; then
        section "Downloading AIDA (first start: about 3 GB, a few minutes)"
    else
        section "Downloading the images for this version"
    fi
    # One service at a time, to know which downloads failed.
    to_build=()
    for svc in "${to_pull[@]}"; do
        compose pull "$svc" && continue
        case "$svc" in
            # AIDA's own images can be built from this checkout instead —
            # e.g. no prebuilt image for this CPU (Apple Silicon) yet.
            backend|frontend|aida-pentest) to_build+=("$svc") ;;
            *)
                if image_missing "$(service_image "$svc")"; then
                    die "Could not download the $svc image." "Check your internet connection, then run: aida start"
                fi
                warn "Could not check for a newer $svc image — using the one already here." ;;
        esac
    done
    if [[ ${#to_build[@]} -gt 0 ]]; then
        section "Building ${to_build[*]} from source (no image to download for this machine)"
        echo "  ${DIM}The first build can take 10-20 minutes; later starts reuse it.${NC}"
        compose build "${to_build[@]}" \
            || die "Could not build ${to_build[*]}." "See the error above, or ask for help with the output of: aida doctor"
    fi
    $DEV || echo "$head_commit" > .aida/last-pull
fi

# ==============================================================================
# Start
# ==============================================================================

section "Starting AIDA"
if $DEV; then
    # The HTTPS front door is disabled in dev; don't leave a prod one running.
    docker rm -f aida_caddy >/dev/null 2>&1 || true
fi
compose up -d --remove-orphans "${SERVICES[@]}"

printf "  Waiting for the backend... "
if ! wait_until 120 curl -fsS --max-time 3 "$AIDA_BACKEND_URL/health"; then
    echo "${RED}timeout${NC}"
    die "The backend did not start." "See what went wrong: aida logs backend"
fi
echo "${GREEN}ready${NC}"

printf "  Waiting for the web UI...  "
if $DEV; then
    ui_check=(curl -fsS --max-time 3 http://localhost:5173)
else
    ui_check=(curl -fsSk --max-time 3 "https://localhost:${AIDA_PORT}/")
fi
if ! wait_until 120 "${ui_check[@]}"; then
    echo "${RED}timeout${NC}"
    if $DEV; then
        die "The web UI did not start." "See what went wrong: aida logs frontend"
    fi
    die "The web UI did not start." "See what went wrong: aida logs caddy (and aida logs frontend)"
fi
echo "${GREEN}ready${NC}"

# Host helper: lets the UI open workspace folders and terminals on this
# machine. Optional, needs python3.
pkill -f "tools/helper.py" 2>/dev/null || true
if command -v python3 >/dev/null 2>&1; then
    AIDA_PORT="$AIDA_PORT" nohup python3 "$AIDA_ROOT/tools/helper.py" >/dev/null 2>&1 &
fi

# ==============================================================================
# Done
# ==============================================================================

section "AIDA is running"
echo
if $DEV; then
    echo "  Web UI     ${BOLD}http://localhost:5173${NC}   (hot reload)"
    echo "  API        http://localhost:8000/docs"
    print_setup_code http://localhost:5173
else
    print_urls
    echo "  ${DIM}Your browser will warn about the self-signed certificate: that's expected,"
    echo "  continue to the site. To remove the warning on this machine: aida trust${NC}"
    print_setup_code
fi
echo
echo "  Next: create an assessment in the web UI, then launch the agent:"
echo "    ${BOLD}aida run \"<assessment>\"${NC}        Claude Code inside the assessment's container"
echo "    ${BOLD}aida --assessment \"<assessment>\"${NC}  or with Claude Code / Codex installed here"
echo
echo "  ${DIM}aida status · aida logs · aida stop · aida update · aida doctor${NC}"
echo
